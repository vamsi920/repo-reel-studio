#!/usr/bin/env node
/**
 * Generates docs/environment-variables.md from config/environment-requirements.json.
 *
 * Three env templates (.env, .env.example, .env.sample) and NETLIFY_ENV_SETUP.md
 * disagreed with each other and with the live app -- NETLIFY_ENV_SETUP.md still
 * documented Firebase variables the current frontend never reads. Rather than
 * hand-reconciling four files that will drift again, the requirement graph is
 * the source of truth and this file is derived from it.
 *
 * Run: npm run docs:env   (CI re-runs it and fails on a diff)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const requirements = JSON.parse(
  readFileSync(resolve(ROOT, "config", "environment-requirements.json"), "utf8"),
);

const SCOPE_TITLES = {
  netlify: "Frontend build (Netlify environment variables)",
  fly: "Agent-server container (Fly secrets / Docker env)",
  "supabase-edge": "Supabase Edge Function secrets",
};

const SCOPE_NOTES = {
  netlify:
    "`VITE_*` variables are baked into the bundle at build time and are visible to anyone who loads the app. Never put a service-role key or any other server secret here. Changing one of these requires a redeploy, not just a restart.",
  fly: "Set with `fly secrets set` on the agent-server app. `OH_SECRET_KEY` is generated and persisted automatically on first boot if unset.",
  "supabase-edge":
    "Set with `supabase secrets set`. `SUPABASE_URL`, `SUPABASE_ANON_KEY` and `SUPABASE_SERVICE_ROLE_KEY` are injected by the platform and do not need to be set by hand.",
};

const lines = [];
lines.push("<!-- GENERATED FILE -- edit config/environment-requirements.json instead.");
lines.push("     Regenerate with: npm run docs:env -->");
lines.push("");
lines.push("# Environment variables");
lines.push("");
lines.push(
  "Every variable this deployment reads, grouped by where it is set. Generated from the requirement graph that also drives the Environment section in the app (`/environment`) and `npm run preflight`.",
);
lines.push("");

for (const [scope, title] of Object.entries(SCOPE_TITLES)) {
  const vars = requirements.envVars.filter((entry) => entry.scope === scope);
  if (vars.length === 0) continue;
  lines.push(`## ${title}`);
  lines.push("");
  lines.push(SCOPE_NOTES[scope]);
  lines.push("");
  lines.push("| Variable | Secret | Expected | Notes |");
  lines.push("| --- | --- | --- | --- |");
  for (const entry of vars) {
    const notes = entry.autoGenerated ? "Auto-generated on first boot if unset." : "";
    lines.push(
      `| \`${entry.name}\` | ${entry.secret ? "yes" : "no"} | ${entry.expected ? `\`${entry.expected}\`` : "—"} | ${notes} |`,
    );
  }
  lines.push("");
}

if (requirements.envPairs.length > 0) {
  lines.push("## Variables that must match each other");
  lines.push("");
  lines.push(
    "Nothing syncs these automatically. Drift is the single most common cause of a broken install, and it does not look like a configuration error — it looks like intermittent authentication failures.",
  );
  lines.push("");
  for (const pair of requirements.envPairs) {
    lines.push(
      `- \`${pair.a.name}\` (${pair.a.scope}) **must equal** \`${pair.b.name}\` (${pair.b.scope}).`,
    );
    if (pair.$comment) lines.push(`  ${pair.$comment}`);
  }
  lines.push("");
}

lines.push("## Outbound network");
lines.push("");
lines.push(
  "Required from the host running the agent-server. `npm run preflight` verifies these from that host — an egress check run anywhere else describes a different network.",
);
lines.push("");
lines.push("| Host | Port | Mirrorable |");
lines.push("| --- | --- | --- |");
for (const entry of requirements.platformEgress) {
  lines.push(`| \`${entry.host}\` | ${entry.port} | ${entry.mirrorable ? "yes" : "no"} |`);
}
lines.push("");
lines.push("Feature-dependent hosts (needed only when the listed feature is used):");
lines.push("");
lines.push("| Host | Port | Required for |");
lines.push("| --- | --- | --- |");
for (const entry of requirements.featureEgress) {
  lines.push(
    `| \`${entry.host}\` | ${entry.port} | ${(entry.requiredFor ?? []).map((f) => `\`${f}\``).join(", ") || "—"} |`,
  );
}
lines.push("");
lines.push(
  "Hosts marked mirrorable can be pointed at an internal registry through `ENVIRONMENT_MIRRORS`, e.g. `{\"registry.npmjs.org\":\"nexus.corp/npm\"}`. The rest cannot; an air-gapped install must replace the capability instead (for example, a self-hosted LLM in place of `generativelanguage.googleapis.com`).",
);
lines.push("");

lines.push("## Host prerequisites");
lines.push("");
lines.push("| Binary | Minimum | Required |");
lines.push("| --- | --- | --- |");
for (const entry of requirements.hostBinaries) {
  lines.push(
    `| \`${entry.name}\` | ${entry.minVersion ?? "—"} | ${entry.optional ? "optional" : "yes"} |`,
  );
}
lines.push("");

lines.push("## Postgres extensions");
lines.push("");
lines.push("| Extension | Required |");
lines.push("| --- | --- |");
for (const entry of requirements.pgExtensions) {
  lines.push(`| \`${entry.name}\` | ${entry.optional ? "optional" : "yes"} |`);
}
lines.push("");

writeFileSync(resolve(ROOT, "docs", "environment-variables.md"), `${lines.join("\n")}\n`);
process.stdout.write("docs/environment-variables.md written\n");
