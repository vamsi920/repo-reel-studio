// KnowledgePage-driven manifest — builds on a DeepWiki-normalized page
// instead of hand-picked conversation files. Still fully deterministic: no
// LLM call in this path. See src/lib/knowledge/knowledge-engine.ts for the
// KnowledgePage/RepositorySnapshot/KnowledgeDiagram shapes.
// ---------------------------------------------------------------------------

interface KtKnowledgeDiagram {
  id: string;
  type: "architecture" | "dependency" | "flow" | "sequence" | "other";
  mermaid: string;
}

interface KtKnowledgePage {
  id: string;
  title: string;
  description: string;
  relevantFiles: { path: string }[];
  diagrams: KtKnowledgeDiagram[];
}

function buildKnowledgeIntroScene(id: number, page: KtKnowledgePage): KtScene {
  const sentence: KtSentence = {
    sentence: page.description || `Let's walk through ${page.title}.`,
    source_refs: [],
    on_screen_focus: [],
  };
  const narration_text = sentence.sentence;
  const words = narration_text.trim().split(/\s+/).filter(Boolean).length;
  const duration_seconds = Math.max(
    MIN_SCENE_SECONDS,
    Math.ceil(words / WORDS_PER_SECOND) + 2,
  );

  return {
    id,
    type: "intro",
    file_path: null,
    title: page.title,
    code: "",
    highlight_lines: [1, 1],
    narration_text,
    sentences: [sentence],
    focus_symbols: [],
    durationInFrames: Math.round(duration_seconds * FPS),
    startFrame: 0,
    endFrame: 0,
  };
}

const DIAGRAM_SCENE_TYPE: Record<KtKnowledgeDiagram["type"], KtSceneType> = {
  architecture: "architecture",
  dependency: "architecture",
  flow: "flow",
  sequence: "flow",
  other: "diagram",
};

function buildDiagramScene(
  id: number,
  pageTitle: string,
  diagram: KtKnowledgeDiagram,
): KtScene {
  const sentence: KtSentence = {
    sentence: `Here's the real ${diagram.type} diagram for ${pageTitle}, generated from the actual codebase.`,
    source_refs: [],
    on_screen_focus: [],
  };
  const narration_text = sentence.sentence;
  const words = narration_text.trim().split(/\s+/).filter(Boolean).length;
  const duration_seconds = Math.max(
    MIN_SCENE_SECONDS,
    Math.ceil(words / WORDS_PER_SECOND) + 2,
  );

  return {
    id,
    type: DIAGRAM_SCENE_TYPE[diagram.type],
    file_path: null,
    title: pageTitle,
    code: "",
    highlight_lines: [1, 1],
    narration_text,
    sentences: [sentence],
    focus_symbols: [],
    durationInFrames: Math.round(duration_seconds * FPS),
    startFrame: 0,
    endFrame: 0,
    mermaid: diagram.mermaid,
  };
}

function buildRepoTreeScene(
  id: number,
  pageTitle: string,
  repoFiles: string[],
): KtScene | null {
  if (!repoFiles.length) return null;
  const shown = repoFiles.slice(0, 40);
  const sentence: KtSentence = {
    sentence: `Here's where ${pageTitle} lives in the repo — ${repoFiles.length} file${repoFiles.length === 1 ? "" : "s"} in scope.`,
    source_refs: [],
    on_screen_focus: shown.slice(0, 6),
  };
  const narration_text = sentence.sentence;
  const words = narration_text.trim().split(/\s+/).filter(Boolean).length;
  const duration_seconds = Math.max(
    MIN_SCENE_SECONDS,
    Math.ceil(words / WORDS_PER_SECOND) + 2,
  );

  return {
    id,
    type: "repo-tree",
    file_path: null,
    title: pageTitle,
    code: "",
    highlight_lines: [1, 1],
    narration_text,
    sentences: [sentence],
    focus_symbols: [],
    durationInFrames: Math.round(duration_seconds * FPS),
    startFrame: 0,
    endFrame: 0,
    tree_files: shown,
  };
}

/**
 * Builds a deterministic KT-video manifest from a DeepWiki-normalized
 * KnowledgePage instead of hand-picked conversation files. No LLM call —
 * reuses the same real-file/real-symbol extraction as buildKtManifest, just
 * scoped to the page's relevantFiles, and renders the page's real Mermaid
 * diagrams (never re-generating them) as their own scenes.
 *
 * `fileContents` must already contain the real text of every path in
 * `page.relevantFiles` (the caller resolves these from the same repository
 * snapshot DeepWiki analyzed — see kt-page.tsx). `repoFiles` is the full
 * file list shown in an optional repo-tree scene.
 */
export function buildKtManifestFromKnowledgePage(
  page: KtKnowledgePage,
  fileContents: Record<string, string>,
  repoFiles: string[] = [],
  maxCodeScenes = 5,
): KtManifest {
  const scenes: KtScene[] = [];
  let id = 0;

  scenes.push(buildKnowledgeIntroScene(id, page));
  id += 1;

  for (const diagram of page.diagrams) {
    scenes.push(buildDiagramScene(id, page.title, diagram));
    id += 1;
  }

  if (!page.diagrams.length) {
    const treeScene = buildRepoTreeScene(id, page.title, repoFiles);
    if (treeScene) {
      scenes.push(treeScene);
      id += 1;
    }
  }

  const codeScenes: KtScene[] = [];
  for (const { path } of page.relevantFiles.slice(0, maxCodeScenes)) {
    const content = fileContents[path];
    if (!content?.trim()) continue;
    const scene = buildCodeScene(id, path, content);
    scenes.push(scene);
    codeScenes.push(scene);
    id += 1;
  }

  const summary = buildSummaryScene(id, page.title, codeScenes);
  if (summary) {
    scenes.push(summary);
    id += 1;
  }

  let cursor = 0;
  for (const scene of scenes) {
    scene.startFrame = cursor;
    cursor += scene.durationInFrames;
    scene.endFrame = cursor;
  }

  return {
    repo_name: page.title,
    scenes,
    totalFrames: Math.max(1, cursor),
    fps: FPS,
    repo_files: repoFiles,
  };
}
