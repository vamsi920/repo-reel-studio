/**
 * BRAIN.md: the one map every agent reads first.
 *
 * Written into the workspace at `.neodevex/brain/BRAIN.md` (git-excluded,
 * like the KT docs), so any agent in the folder — Neo's, or Claude Code /
 * Cursor / Codex run by a teammate — starts from the same project knowledge
 * instead of a private chat history. It is a rendering of workspace memory,
 * never a second source of truth: regenerate, don't edit.
 *
 * Content is written base64-encoded, never interpolated into a command.
 */
import {
  MEMORY_BLOCK_END,
  MEMORY_BLOCK_START,
} from "#/lib/workspace-memory/markers";
import type { MemoryRecord } from "#/lib/workspace-memory/types";

import { BRAIN_LAYERS, KIND_TO_LAYER, type BrainLayer } from "./types";

export const BRAIN_DIR = ".neodevex/brain";
export const BRAIN_MAP_FILE = `${BRAIN_DIR}/BRAIN.md`;
const GIT_EXCLUDE_ENTRY = ".neodevex/";
const MAX_PER_LAYER = 25;
const MAX_CHUNK_B64_CHARS = 60_000;

const LAYER_HEADINGS: Record<BrainLayer, string> = {
  gate: "Gates (never without explicit approval)",
  decision: "Decisions",
  policy: "Policies",
  convention: "Conventions",
  skill: "Skills (how to run things here)",
  failure: "Known failures and their fixes",
  fact: "Facts",
};

const SOURCE_LABELS: Record<string, string> = {
  "user-decision": "user",
  "approved-requirement": "requirement",
  "verified-agent-result": "run",
  "test-result": "test run",
  "pr-outcome": "PR",
  "sme-validated": "SME",
  "knowledge-reference": "KT docs",
  "uploaded-document": "document",
  "repository-evidence": "repo",
  incident: "incident",
};

export interface BrainMapInput {
  records: readonly MemoryRecord[];
  pendingReview: number;
  generatedAt: string;
  projectName?: string;
}

/**
 * One hidden line per message telling the agent the map exists. Wrapped in
 * the memory markers so the chat hides it like the memory block.
 */
export function brainMapPointer(): string {
  return [
    MEMORY_BLOCK_START,
    `Project brain: read ${BRAIN_MAP_FILE} before planning; follow its gates, decisions and conventions.`,
    MEMORY_BLOCK_END,
  ].join("\n");
}

function line(record: MemoryRecord): string {
  const source =
    SOURCE_LABELS[record.provenance.source] ?? record.provenance.source;
  const day = record.provenance.observedAt.slice(0, 10);
  const marks = [
    record.pinned ? "pinned" : null,
    record.status === "conflicted" ? "CONFLICT" : null,
    record.tags.includes("stale") ? "stale" : null,
  ].filter(Boolean);
  const suffix = marks.length ? `, ${marks.join(", ")}` : "";
  return `- ${record.statement} _(${source}, ${day}${suffix})_`;
}

function rank(a: MemoryRecord, b: MemoryRecord): number {
  if (a.pinned !== b.pinned) return a.pinned ? -1 : 1;
  if (b.confidence !== a.confidence) return b.confidence - a.confidence;
  return (
    Date.parse(b.provenance.observedAt) - Date.parse(a.provenance.observedAt)
  );
}

export function renderBrainMap(input: BrainMapInput): string {
  const live = input.records.filter((record) => record.status !== "superseded");
  const byLayer = new Map<BrainLayer, MemoryRecord[]>();
  live.forEach((record) => {
    const layer = KIND_TO_LAYER[record.kind] ?? "fact";
    byLayer.set(layer, [...(byLayer.get(layer) ?? []), record]);
  });

  const out: string[] = [
    `# Project brain${input.projectName ? `: ${input.projectName}` : ""}`,
    "",
    `_Maintained by Neo in the background from this project's conversations and runs. Updated ${input.generatedAt}. ${live.length} active learning(s)._`,
    "",
    "## Read this first",
    "",
    "- Follow every gate below; ask the user before any gated action.",
    "- When sources disagree, trust in this order: user decisions > approved requirements > test and run results > repository evidence > KT docs. Newer beats older within the same source.",
    "- CONFLICT means two trusted sources disagree: ask, do not pick one.",
    "- If what you need is not here, say it is missing. Do not guess, and never present a guess as project knowledge.",
    '- This file is generated. To teach Neo, tell it in chat ("always ...", "use X instead of Y", "we decided ..."); do not edit this file.',
    "",
    "## Map",
    "",
    "- Architecture and code walkthroughs: `.neodevex/kt/INDEX.md` (if present)",
    "- Full memory trail, including superseded entries: `.neodevex/memory/records.jsonl`",
    "",
  ];

  BRAIN_LAYERS.forEach((layer) => {
    const entries = (byLayer.get(layer) ?? [])
      .sort(rank)
      .slice(0, MAX_PER_LAYER);
    if (entries.length === 0) return;
    out.push(`## ${LAYER_HEADINGS[layer]}`, "", ...entries.map(line), "");
  });

  if (live.length === 0) {
    out.push("_Nothing learned yet for this project._", "");
  }
  if (input.pendingReview > 0) {
    out.push(
      `_${input.pendingReview} more learning(s) are waiting for a person to review them and are not trusted yet._`,
      "",
    );
  }
  return `${out.join("\n").trimEnd()}\n`;
}

function encodePayload(text: string): string {
  if (typeof btoa === "function") {
    const bytes = new TextEncoder().encode(text);
    let binary = "";
    bytes.forEach((byte) => {
      binary += String.fromCharCode(byte);
    });
    return btoa(binary);
  }
  return Buffer.from(text, "utf-8").toString("base64");
}

/**
 * Shell commands that write the map, run from the workspace root. Waits for a
 * git checkout (a repo conversation clones into an empty folder first) and
 * keeps `.neodevex/` out of the user's commits.
 */
export function buildBrainMapCommands(content: string): string[] {
  const prepare = [
    "test -e .git",
    `mkdir -p ${BRAIN_DIR}`,
    `if [ -d .git/info ]; then grep -qxF '${GIT_EXCLUDE_ENTRY}' .git/info/exclude 2>/dev/null || echo '${GIT_EXCLUDE_ENTRY}' >> .git/info/exclude; fi`,
  ].join(" && ");
  const encoded = encodePayload(content);
  const chunkSize = MAX_CHUNK_B64_CHARS - (MAX_CHUNK_B64_CHARS % 4);
  const tmp = `${BRAIN_MAP_FILE}.tmp`;
  const writes: string[] = [];
  for (let offset = 0; offset < encoded.length; offset += chunkSize) {
    const chunk = encoded.slice(offset, offset + chunkSize);
    writes.push(
      `printf '%s' '${chunk}' | base64 -d ${offset === 0 ? ">" : ">>"} ${tmp}`,
    );
  }
  // Rename last so a reader never sees half a map.
  return [prepare, ...writes, `mv -f ${tmp} ${BRAIN_MAP_FILE}`];
}

/** Cheap change detector so the map is only rewritten when it changed. */
export function mapFingerprint(content: string): string {
  // The timestamp line changes every render; ignore it.
  const stable = content
    .split("\n")
    .filter((row) => !row.startsWith("_Maintained by Neo"))
    .join("\n");
  let hash = 5381;
  for (let index = 0; index < stable.length; index += 1) {
    hash = (hash * 33 + stable.charCodeAt(index)) % 4_294_967_296;
  }
  return hash.toString(36);
}
